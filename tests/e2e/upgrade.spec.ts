import { expect, test } from './fixtures'
import { campaignSeeds } from '../../src/engine/campaign'

test('preserves guest progress, supports sign-in and separates two local profiles', async ({ page }) => {
  await page.goto('/#/play/nim/0')
  await page.getByRole('button', { name: /Đống 3 · 4 viên/ }).click()
  await page.getByRole('button', { name: 'Lấy 1 viên', exact: true }).click()
  await expect(page.getByTestId('move-count')).toHaveText('1')

  await page.getByRole('link', { name: 'Tài khoản' }).click()
  await page.getByRole('button', { name: 'Tạo hồ sơ', exact: true }).click()
  await expect(page.getByLabel('Sao chép tiến độ khách vào hồ sơ mới')).toBeChecked()
  await page.getByLabel('Tên hồ sơ').fill('Kiên')
  await page.getByLabel('Mật khẩu').fill('DauTruong2026!')
  await page.getByRole('button', { name: 'Tạo và đăng nhập' }).click()
  await expect(page.getByRole('link', { name: 'Hồ sơ Kiên' })).toBeVisible()
  await page.goto('/#/play/nim/0')
  await expect(page.getByTestId('move-count')).toHaveText('1')
  await page.getByRole('button', { name: 'Lấy 1 viên', exact: true }).click()
  await expect(page.getByTestId('move-count')).toHaveText('2')

  await page.reload()
  await expect(page.getByRole('link', { name: 'Hồ sơ Kiên' })).toBeVisible()
  await expect(page.getByTestId('move-count')).toHaveText('2')
  await page.getByRole('link', { name: 'Hồ sơ Kiên' }).click()
  await page.getByRole('button', { name: 'Đăng xuất' }).click()
  await page.goto('/#/play/nim/0')
  await expect(page.getByTestId('move-count')).toHaveText('1')

  await page.getByRole('link', { name: 'Tài khoản' }).click()
  await page.getByRole('button', { name: 'Tạo hồ sơ', exact: true }).click()
  await page.getByLabel('Sao chép tiến độ khách vào hồ sơ mới').uncheck()
  await page.getByLabel('Tên hồ sơ').fill('Linh')
  await page.getByLabel('Mật khẩu').fill('AnotherSafePass')
  await page.getByRole('button', { name: 'Tạo và đăng nhập' }).click()
  await expect(page.getByRole('link', { name: 'Hồ sơ Linh' })).toBeVisible()
  await page.goto('/#/play/nim/0')
  await expect(page.getByTestId('move-count')).toHaveText('0')
  await page.getByRole('link', { name: 'Hồ sơ Linh' }).click()
  await page.getByRole('button', { name: 'Đăng xuất' }).click()

  await page.getByLabel('Tên hồ sơ').fill('KIÊN')
  await page.getByLabel('Mật khẩu').fill('not the password')
  await page.getByRole('button', { name: 'Đăng nhập vào game' }).click()
  await expect(page.getByRole('alert')).toHaveText('Tên hồ sơ hoặc mật khẩu không đúng.')
  await page.getByLabel('Mật khẩu').fill('DauTruong2026!')
  await page.getByRole('button', { name: 'Đăng nhập vào game' }).click()
  await expect(page.getByRole('link', { name: 'Hồ sơ Kiên' })).toBeVisible()
  await page.goto('/#/play/nim/0')
  await expect(page.getByTestId('move-count')).toHaveText('2')
})

test('the bank exposes multiple distinct playable boards and marks locked ranks', async ({ page }) => {
  await page.setViewportSize({ width: 340, height: 780 })
  await page.goto('/#/games/graph')
  await expect(page.locator('.level-row')).toHaveCount(4)
  await expect(page.getByText('0/4 đã giải')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(340)
  await page.getByRole('navigation', { name: 'Cấp độ' }).getByRole('link', { name: /Olympiad/ }).click()
  await expect(page.getByText('Hoàn thành một bài ở cấp trước để mở.')).toBeVisible()
  await expect(page.locator('.level-row').getByRole('link')).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Cấp độ' }).getByRole('link', { name: /Apprentice/ }).click()
  await page.getByRole('link', { name: 'Chơi bài 2', exact: true }).click()
  expect(decodeURIComponent(page.url())).toContain(campaignSeeds[1])
  await expect(page.getByRole('heading', { name: 'Chu trình chẵn' })).toBeVisible()
  await expect(page.locator('.svg-node')).toHaveCount(4)
  await page.getByRole('button', { name: 'Đỉnh 1' }).click()
  await expect(page.getByTestId('move-count')).toHaveText('1')
  await page.reload()
  await expect(page.getByTestId('move-count')).toHaveText('1')
})
